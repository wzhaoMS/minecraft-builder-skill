export const FONTS = Object.freeze({
  '5x7': { width: 5, height: 7, glyphs: G57, space: 3, lowercase: true },
  '3x5': { width: 3, height: 5, glyphs: G35, space: 2, lowercase: false },
});

function glyphFor(font, ch) {
  const f = FONTS[font];
  let rows = f.glyphs[ch];
  if (!rows && !f.lowercase) rows = f.glyphs[ch.toUpperCase()];
  if (!rows) rows = f.glyphs[ch.toUpperCase()] ?? f.glyphs[ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '')] ?? f.glyphs['?'];
  return rows;
}

/** Columns [first, last] that contain ink (null for an empty glyph). */
function inkRange(rows) {
  let a = Infinity, b = -Infinity;
  for (const r of rows) for (let i = 0; i < r.length; i++) if (r[i] === '#') { if (i < a) a = i; if (i > b) b = i; }
  return a === Infinity ? null : [a, b];
}

/**
 * Lay out text as a bitmap.
 * @param {string} text  multi-line via '\n'
 * @param {{ font?: '5x7'|'3x5', spacing?: number, lineSpacing?: number, scale?: number,
 *           monospace?: boolean, align?: 'left'|'center'|'right' }} [opts]
 * @returns {{ width: number, height: number, pixels: (x: number, y: number) => boolean,
 *             lines: number, toString: () => string }}  y = 0 is the top row
 */
export function textBitmap(text, { font = '5x7', spacing = 1, lineSpacing = 1, scale = 1, monospace = false, align = 'left' } = {}) {
  const f = FONTS[font];
  if (!f) throw new Error(`Unknown font "${font}" (use ${Object.keys(FONTS).join(' | ')})`);
  scale = Math.max(1, Math.floor(scale));
  spacing = Math.max(0, Math.floor(spacing));
  lineSpacing = Math.max(0, Math.floor(lineSpacing));
  const lines = String(text ?? '').replace(/\r\n?/g, '\n').split('\n');
  // per line: list of [glyphRows|null, x0, x1] columns to copy
  const laid = lines.map((line) => {
    const cells = [];
    let w = 0;
    for (const ch of [...line]) {
      if (cells.length) w += spacing;
      if (ch === ' ' || ch === '\t') {
        const sw = monospace ? f.width : f.space;
        cells.push({ rows: null, from: 0, to: sw - 1, x: w });
        w += sw;
        continue;
      }
      const rows = glyphFor(font, ch);
      let range = monospace ? [0, f.width - 1] : inkRange(rows) ?? [0, f.space - 1];
      cells.push({ rows, from: range[0], to: range[1], x: w });
      w += range[1] - range[0] + 1;
    }
    return { cells, width: w };
  });
  const innerW = Math.max(0, ...laid.map((l) => l.width));
  const innerH = lines.length * f.height + (lines.length - 1) * lineSpacing;
  const W = innerW * scale, H = innerH * scale;
  const data = new Uint8Array(Math.max(1, innerW * innerH));
  laid.forEach((l, li) => {
    const off = align === 'center' ? Math.floor((innerW - l.width) / 2) : align === 'right' ? innerW - l.width : 0;
    const y0 = li * (f.height + lineSpacing);
    for (const c of l.cells) {
      if (!c.rows) continue;
      for (let r = 0; r < f.height; r++) {
        const row = c.rows[r] ?? '';
        for (let i = c.from; i <= c.to; i++) if (row[i] === '#') data[(y0 + r) * innerW + off + c.x + (i - c.from)] = 1;
      }
    }
  });
  const pixels = (x, y) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return false;
    return data[Math.floor(y / scale) * innerW + Math.floor(x / scale)] === 1;
  };
  return {
    width: W,
    height: H,
    lines: lines.length,
    pixels,
    toString() {
      const out = [];
      for (let y = 0; y < H; y++) {
        let row = '';
        for (let x = 0; x < W; x++) row += pixels(x, y) ? '#' : '.';
        out.push(row);
      }
      return out.join('\n');
    },
  };
}

/** Characters supported by a font (besides space). */
export function fontChars(font = '5x7') {
  return Object.keys(FONTS[font]?.glyphs ?? {}).join('');
}
