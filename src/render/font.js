export const FONTS = {
  '5x7': { glyphs: G5, width: 5, height: 7 },
  '3x5': { glyphs: G3, width: 3, height: 5 },
};

function glyphFor(font, ch) {
  const g = font.glyphs;
  return g[ch] ?? g[ch.toUpperCase()] ?? g[ch.toLowerCase()] ?? g['?'];
}

/** Width in columns of one glyph (trimmed proportional width for narrow glyphs like I, 1, !). */
function glyphWidth(font, rows, proportional) {
  if (!proportional) return font.width;
  let min = font.width, max = -1;
  for (const r of rows) for (let x = 0; x < r.length; x++) if (r[x] === '#') { if (x < min) min = x; if (x > max) max = x; }
  return max < 0 ? Math.max(2, Math.ceil(font.width / 2)) : max - min + 1;
}

/**
 * Rasterise text. Lines split on "\n".
 * @param {string} text
 * @param {{ font?: '5x7'|'3x5', scale?: number, spacing?: number, lineSpacing?: number, proportional?: boolean }} [opts]
 * @returns {{ width: number, height: number, pixels: (x:number, y:number) => boolean, set: Set<string> }}
 */
export function textBitmap(text, { font = '5x7', scale = 1, spacing = 1, lineSpacing = 1, proportional = false } = {}) {
  const f = FONTS[font];
  if (!f) throw new Error(`Unknown font "${font}" (5x7 | 3x5)`);
  const set = new Set();
  const lines = String(text).split(/\r?\n/);
  let width = 0;
  lines.forEach((line, li) => {
    let cx = 0;
    const top = li * (f.height + lineSpacing);
    for (const ch of [...line]) {
      const rows = glyphFor(f, ch);
      const w = glyphWidth(f, rows, proportional);
      let minCol = 0;
      if (proportional) {
        minCol = f.width;
        for (const r of rows) for (let x = 0; x < r.length; x++) if (r[x] === '#' && x < minCol) minCol = x;
        if (minCol === f.width) minCol = 0;
      }
      rows.forEach((r, y) => {
        for (let x = 0; x < r.length; x++) if (r[x] === '#') set.add(`${cx + x - minCol},${top + y}`);
      });
      cx += w + spacing;
    }
    width = Math.max(width, cx - spacing);
  });
  const height = lines.length * f.height + (lines.length - 1) * lineSpacing;
  if (scale === 1) return { width, height, pixels: (x, y) => set.has(`${x},${y}`), set };
  const scaled = new Set();
  for (const k of set) {
    const [x, y] = k.split(',').map(Number);
    for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) scaled.add(`${x * scale + dx},${y * scale + dy}`);
  }
  return { width: width * scale, height: height * scale, pixels: (x, y) => scaled.has(`${x},${y}`), set: scaled };
}
